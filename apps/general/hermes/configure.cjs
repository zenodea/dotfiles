#!/usr/bin/env node
'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { isDeepStrictEqual } = require('node:util');

const OWNER = 'dotfiles-hermes-palette-v1';
const SKIN_HEADER = '# Generated by dotfiles Hermes palette integration; do not edit.';
const PROFILE_RE = /^[a-z0-9][a-z0-9_-]{0,63}$/;
const HEX_RE = /^[0-9a-fA-F]{6}$/;
const THEME_RE = /^[a-z0-9][a-z0-9_-]{0,63}$/;
const COLORS = [
  'BG', 'SURFACE', 'BG_ALT', 'BORDER', 'MUTED', 'FG', 'FG_BRIGHT',
  'ACCENT', 'BLUE', 'RED', 'GREEN', 'YELLOW', 'ORANGE', 'PURPLE'
];
const MAX_CONFIG_BYTES = 1_000_000;
const MAX_SKIN_BYTES = 256_000;
const MAX_STAGE_BYTES = 512_000;

class SafetyError extends Error {}

function fail(message) {
  throw new SafetyError(message);
}

function hash(value) {
  return crypto.createHash('sha256').update(value).digest('hex');
}

function isInside(parent, child) {
  const relative = path.relative(parent, child);
  return relative === '' || (!relative.startsWith(`..${path.sep}`) && relative !== '..' && !path.isAbsolute(relative));
}

function absoluteEnvPath(value, fallback, label) {
  const result = value || fallback;
  if (!result || !path.isAbsolute(result)) fail(`${label} must be an absolute path`);
  return path.normalize(result);
}

function existingDirectory(directory, label) {
  let stat;
  try {
    stat = fs.lstatSync(directory);
  } catch (error) {
    if (error.code === 'ENOENT') return false;
    fail(`cannot inspect ${label}`);
  }
  if (stat.isSymbolicLink() || !stat.isDirectory()) fail(`${label} is not a safe directory`);
  return true;
}

function trustedAnchor(home, target) {
  const homeParent = path.dirname(home);
  return isInside(homeParent, target) ? homeParent : path.dirname(target);
}

function assertDirectoryRoute(anchor, target, label) {
  if (!isInside(anchor, target) || !existingDirectory(anchor, `${label} anchor`)) {
    fail(`${label} has no safe parent route`);
  }
  const relative = path.relative(anchor, target);
  let current = anchor;
  for (const part of relative.split(path.sep).filter(Boolean)) {
    current = path.join(current, part);
    let stat;
    try {
      stat = fs.lstatSync(current);
    } catch (error) {
      if (error.code === 'ENOENT') return;
      fail(`cannot inspect ${label} route`);
    }
    if (stat.isSymbolicLink() || !stat.isDirectory()) fail(`${label} route is not safe`);
  }
}

function safeRegularFile(file, label, maxBytes, optional = false) {
  let stat;
  try {
    stat = fs.lstatSync(file);
  } catch (error) {
    if (optional && error.code === 'ENOENT') return null;
    if (error.code === 'ENOENT') fail(`${label} is missing`);
    fail(`cannot inspect ${label}`);
  }
  if (stat.isSymbolicLink() || !stat.isFile() || stat.nlink !== 1) {
    fail(`${label} is not a safe regular file`);
  }
  if (stat.size > maxBytes) fail(`${label} is too large`);
  return stat;
}

function readSafeFile(file, label, maxBytes) {
  safeRegularFile(file, label, maxBytes);
  try {
    return fs.readFileSync(file, 'utf8');
  } catch {
    fail(`cannot read ${label}`);
  }
}

function ensurePrivateDirectory(root, childParts) {
  if (!existingDirectory(root, 'cache root')) {
    try {
      fs.mkdirSync(root, { recursive: true, mode: 0o700 });
    } catch {
      fail('cannot create cache root');
    }
    if (!existingDirectory(root, 'cache root')) fail('cache root is not a safe directory');
  }

  let current = root;
  for (const part of childParts) {
    current = path.join(current, part);
    if (!existingDirectory(current, 'cache directory')) {
      try {
        fs.mkdirSync(current, { mode: 0o700 });
      } catch (error) {
        if (error.code !== 'EEXIST') fail('cannot create cache directory');
      }
      if (!existingDirectory(current, 'cache directory')) fail('cache directory is not safe');
    }
  }
  return current;
}

function temporaryName(destination) {
  return path.join(path.dirname(destination), `.${path.basename(destination)}.${process.pid}.${crypto.randomBytes(8).toString('hex')}.tmp`);
}

function atomicWrite(destination, content, mode, options = {}) {
  const { label = 'output file', owned = null, expectedHash = null } = options;
  const oldStat = safeRegularFile(destination, label, Math.max(Buffer.byteLength(content), MAX_STAGE_BYTES), true);
  if (oldStat) {
    const old = readSafeFile(destination, label, Math.max(Buffer.byteLength(content), MAX_STAGE_BYTES));
    if (owned && !owned(old)) fail(`${label} is not owned by dotfiles`);
    if (old === content) return false;
  }

  if (!existingDirectory(path.dirname(destination), `${label} parent`)) fail(`${label} parent is not safe`);
  const temp = temporaryName(destination);
  let descriptor;
  try {
    descriptor = fs.openSync(temp, 'wx', mode);
    fs.writeFileSync(descriptor, content, 'utf8');
    fs.fsyncSync(descriptor);
    fs.fchmodSync(descriptor, mode);
    fs.closeSync(descriptor);
    descriptor = undefined;

    if (!existingDirectory(path.dirname(destination), `${label} parent`)) fail(`${label} parent changed`);
    const current = safeRegularFile(destination, label, MAX_CONFIG_BYTES, true);
    if (expectedHash !== null) {
      if (!current) fail(`${label} changed since staging`);
      const currentText = readSafeFile(destination, label, MAX_CONFIG_BYTES);
      if (hash(currentText) !== expectedHash) fail(`${label} changed since staging`);
    } else if (current && owned) {
      const currentText = readSafeFile(destination, label, MAX_STAGE_BYTES);
      if (!owned(currentText)) fail(`${label} is not owned by dotfiles`);
    }
    fs.renameSync(temp, destination);
    return true;
  } catch (error) {
    if (descriptor !== undefined) {
      try { fs.closeSync(descriptor); } catch {}
    }
    try { fs.unlinkSync(temp); } catch {}
    if (error instanceof SafetyError) throw error;
    fail(`cannot atomically write ${label}`);
  }
}

function createBackupOnce(destination, source) {
  const present = safeRegularFile(destination, 'config backup', MAX_CONFIG_BYTES, true);
  if (present) return false;
  if (!existingDirectory(path.dirname(destination), 'config parent')) fail('config parent is not safe');

  const temp = temporaryName(destination);
  let descriptor;
  try {
    descriptor = fs.openSync(temp, 'wx', 0o600);
    fs.writeFileSync(descriptor, source, 'utf8');
    fs.fsyncSync(descriptor);
    fs.fchmodSync(descriptor, 0o600);
    fs.closeSync(descriptor);
    descriptor = undefined;
    if (!existingDirectory(path.dirname(destination), 'config parent')) fail('config parent changed');
    if (safeRegularFile(destination, 'config backup', MAX_CONFIG_BYTES, true)) {
      fs.unlinkSync(temp);
      return false;
    }
    // A same-directory hard link is an atomic create-without-replace operation.
    fs.linkSync(temp, destination);
    fs.unlinkSync(temp);
    return true;
  } catch (error) {
    if (descriptor !== undefined) {
      try { fs.closeSync(descriptor); } catch {}
    }
    try { fs.unlinkSync(temp); } catch {}
    if (error instanceof SafetyError) throw error;
    if (error.code === 'EEXIST') {
      safeRegularFile(destination, 'config backup', MAX_CONFIG_BYTES);
      return false;
    }
    fail('cannot create config backup');
  }
}

function preflightOwnedOutput(destination, label, maxBytes, owned) {
  const stat = safeRegularFile(destination, label, maxBytes, true);
  if (stat && !owned(readSafeFile(destination, label, maxBytes))) {
    fail(`${label} is not owned by dotfiles`);
  }
}

function resolveYaml(hermesHome, home) {
  const candidates = [];
  if (process.env.HERMES_REPO) candidates.push(absoluteEnvPath(process.env.HERMES_REPO, '', 'HERMES_REPO'));
  candidates.push(path.join(hermesHome, 'hermes-agent'));
  candidates.push(path.join(home, '.hermes', 'hermes-agent'));

  const unique = [...new Set(candidates)];
  let installationFound = false;
  for (const candidate of unique) {
    let stat;
    try {
      stat = fs.lstatSync(candidate);
    } catch (error) {
      if (error.code === 'ENOENT') continue;
      fail('cannot inspect Hermes installation');
    }
    if (stat.isSymbolicLink() || !stat.isDirectory()) continue;
    installationFound = true;
    try {
      const resolved = require.resolve('yaml', { paths: [candidate] });
      const packageRoot = path.join(candidate, 'node_modules', 'yaml');
      const realResolved = fs.realpathSync(resolved);
      const realPackageRoot = fs.realpathSync(packageRoot);
      if (!isInside(realPackageRoot, realResolved)) continue;
      return { YAML: require(realResolved), status: null };
    } catch {}
  }
  return { YAML: null, status: installationFound ? 'no-parser' : 'no-installation' };
}

function walkYaml(YAML, node, seen = new Set()) {
  if (!node || typeof node !== 'object' || seen.has(node)) return;
  seen.add(node);
  if (YAML.isAlias(node)) fail('config aliases are not supported');
  if (node.anchor || node.tag) fail('config anchors and tags are not supported');
  if (YAML.isMap(node) || YAML.isSeq(node)) {
    for (const item of node.items) walkYaml(YAML, item, seen);
    return;
  }
  if (YAML.isPair(node)) {
    if (YAML.isScalar(node.key) && node.key.value === '<<') fail('config merge keys are not supported');
    walkYaml(YAML, node.key, seen);
    walkYaml(YAML, node.value, seen);
  }
}

function parseConfig(YAML, source) {
  let documents;
  try {
    documents = YAML.parseAllDocuments(source, { keepSourceTokens: true, maxAliasCount: 0, strict: true, uniqueKeys: true });
  } catch {
    fail('Hermes config YAML is malformed');
  }
  if (documents.length !== 1 || documents[0].errors.length) fail('Hermes config YAML is malformed or has duplicate keys');
  const document = documents[0];
  if (!YAML.isMap(document.contents)) fail('Hermes config must be a mapping');
  walkYaml(YAML, document.contents);
  return document;
}

function pairFor(map, name, YAML) {
  return map.items.find(item => YAML.isPair(item) && YAML.isScalar(item.key) && item.key.value === name);
}

function validateTransformedConfig(YAML, originalDocument, transformed) {
  const transformedDocument = parseConfig(YAML, transformed);
  const actual = transformedDocument.toJS({ maxAliasCount: 0 });
  const expected = originalDocument.toJS({ maxAliasCount: 0 });

  if (!actual.display || typeof actual.display !== 'object' || Array.isArray(actual.display) ||
      actual.display.skin !== 'dotfiles') {
    fail('transformed Hermes config is invalid');
  }
  if (expected.display == null) expected.display = {};
  expected.display.skin = 'dotfiles';
  if (!isDeepStrictEqual(actual, expected)) fail('transformed Hermes config changed unrelated values');
  return transformed;
}

function replaceConfigSkin(YAML, source) {
  const document = parseConfig(YAML, source);
  const root = document.contents;
  let displayPair = pairFor(root, 'display', YAML);
  const checked = transformed => validateTransformedConfig(YAML, document, transformed);

  if (!displayPair) {
    if (root.srcToken?.type !== 'block-map') fail('flow-style root maps are not supported for insertion');
    if (/^(?:\s)*(?:%|---(?:\s|$)|\.\.\.(?:\s|$))/m.test(source)) fail('config document markers are not supported for insertion');
    const prefix = source.length && !source.endsWith('\n') ? '\n' : '';
    return checked(`${source}${prefix}display:\n  skin: dotfiles\n`);
  }

  const display = displayPair.value;
  if (YAML.isMap(display)) {
    if (display.srcToken?.type === 'block-map' && display.srcToken.indent !== 2) {
      fail('display map indentation is not supported');
    }
    const skinPair = pairFor(display, 'skin', YAML);
    if (skinPair) {
      const skin = skinPair.value;
      if (!YAML.isScalar(skin)) fail('display.skin must be a scalar');
      if (skin.srcToken?.type === 'block-scalar') fail('block-scalar display.skin is not supported');
      if (skin.value === 'dotfiles') return source;
      if (!Array.isArray(skin.range)) fail('display.skin has no safe source range');
      if (skin.range[0] === skin.range[1]) {
        const colon = skinPair.srcToken?.sep?.find(token => token.type === 'map-value-ind');
        if (!colon) fail('display.skin has no safe insertion point');
        const offset = colon.offset + colon.source.length;
        return checked(`${source.slice(0, offset)} dotfiles${source.slice(offset)}`);
      }
      return checked(`${source.slice(0, skin.range[0])}dotfiles${source.slice(skin.range[1])}`);
    }

    if (display.srcToken?.type === 'flow-collection') {
      if (display.items.length !== 0 || !Array.isArray(display.range)) fail('flow-style display maps are not supported for insertion');
      return checked(`${source.slice(0, display.range[0])}{ skin: dotfiles }${source.slice(display.range[1])}`);
    }
    if (display.srcToken?.type !== 'block-map' || !Array.isArray(display.range)) {
      fail('display map has no safe insertion point');
    }
    const offset = display.range[1];
    const prefix = offset > 0 && source[offset - 1] !== '\n' ? '\n' : '';
    return checked(`${source.slice(0, offset)}${prefix}  skin: dotfiles\n${source.slice(offset)}`);
  }

  if (YAML.isScalar(display) && display.value == null) {
    if (display.srcToken) fail('explicit null display values are not supported');
    const newline = displayPair.srcToken?.sep?.find(token => token.type === 'newline');
    if (newline) {
      const offset = newline.offset + newline.source.length;
      return checked(`${source.slice(0, offset)}  skin: dotfiles\n${source.slice(offset)}`);
    }
    const colon = displayPair.srcToken?.sep?.find(token => token.type === 'map-value-ind');
    if (!colon) fail('display has no safe insertion point');
    const offset = colon.offset + colon.source.length;
    return checked(`${source.slice(0, offset)}\n  skin: dotfiles${source.slice(offset)}`);
  }

  fail('display must be a mapping');
}

function discoverTargets(hermesHome) {
  if (!existingDirectory(hermesHome, 'HERMES_HOME')) return [];
  const targets = [];

  function add(profile, profileHome) {
    if (!existingDirectory(profileHome, 'profile home')) fail('profile home is not a safe directory');
    const config = path.join(profileHome, 'config.yaml');
    const stat = safeRegularFile(config, 'Hermes config', MAX_CONFIG_BYTES, true);
    if (stat) targets.push({ profile, home: profileHome, config, mode: stat.mode & 0o777 });
  }

  add('default', hermesHome);
  const profiles = path.join(hermesHome, 'profiles');
  let profilesStat;
  try {
    profilesStat = fs.lstatSync(profiles);
  } catch (error) {
    if (error.code !== 'ENOENT') fail('cannot inspect profiles directory');
  }
  if (profilesStat) {
    if (profilesStat.isSymbolicLink() || !profilesStat.isDirectory()) fail('profiles directory is not safe');
    let entries;
    try {
      entries = fs.readdirSync(profiles, { withFileTypes: true });
    } catch {
      fail('cannot read profiles directory');
    }
    for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
      if (!entry.isDirectory() || entry.name === 'default' || !PROFILE_RE.test(entry.name)) continue;
      add(entry.name, path.join(profiles, entry.name));
    }
  }
  return targets;
}

function validatePalette() {
  const palette = {};
  for (const name of COLORS) {
    const value = process.env[name];
    if (!value || !HEX_RE.test(value)) fail(`palette variable ${name} must be exactly six hexadecimal digits`);
    palette[name] = value.toLowerCase();
  }
  const theme = process.env.THEME_NAME;
  if (!theme || !THEME_RE.test(theme)) fail('THEME_NAME is invalid');
  const appearance = process.env.THEME_APPEARANCE;
  if (appearance !== 'dark' && appearance !== 'light') fail('THEME_APPEARANCE must be dark or light');
  return { palette, theme, appearance };
}

function quote(value) {
  return JSON.stringify(value);
}

function skinYaml(palette, theme, appearance) {
  const tokenMap = [
    ['background', 'BG'],
    ['ui_text', 'FG'],
    ['ui_accent', 'ACCENT'],
    ['ui_border', 'BORDER'],
    ['ui_label', 'ACCENT'],
    ['ui_ok', 'GREEN'],
    ['ui_error', 'RED'],
    ['ui_warn', 'YELLOW'],
    ['banner_text', 'FG'],
    ['banner_accent', 'ACCENT'],
    ['banner_title', 'ACCENT'],
    ['banner_border', 'BORDER'],
    ['banner_dim', 'MUTED'],
    ['prompt', 'FG'],
    ['input_rule', 'BORDER'],
    ['response_border', 'ACCENT'],
    ['status_bar_bg', 'BG'],
    ['status_bar_text', 'FG'],
    ['status_bar_strong', 'FG_BRIGHT'],
    ['status_bar_dim', 'MUTED'],
    ['status_bar_good', 'GREEN'],
    ['status_bar_warn', 'YELLOW'],
    ['status_bar_bad', 'ORANGE'],
    ['status_bar_critical', 'RED'],
    ['session_label', 'ACCENT'],
    ['session_border', 'BORDER'],
    ['completion_menu_bg', 'SURFACE'],
    ['completion_menu_current_bg', 'BG_ALT'],
    ['selection_bg', 'BG_ALT'],
    ['shell_dollar', 'BLUE'],
    ['voice_status_bg', 'BG']
  ];
  const lines = [
    SKIN_HEADER,
    'name: dotfiles',
    `description: ${quote(`Dotfiles ${theme} palette (${appearance})`)}`,
    'colors:'
  ];
  for (const [token, color] of tokenMap) lines.push(`  ${token}: "#${palette[color]}"`);
  return `${lines.join('\n')}\n`;
}

function stagePaths(home) {
  const cacheRoot = absoluteEnvPath(process.env.XDG_CACHE_HOME, path.join(home, '.cache'), 'cache root');
  return {
    cacheRoot,
    directory: path.join(cacheRoot, 'dotfiles', 'hermes'),
    skin: path.join(cacheRoot, 'dotfiles', 'hermes', 'dotfiles.yaml'),
    manifest: path.join(cacheRoot, 'dotfiles', 'hermes', 'stage.json')
  };
}

function isOwnedSkin(source) {
  return source.startsWith(`${SKIN_HEADER}\n`);
}

function isOwnedManifest(source) {
  try {
    return JSON.parse(source).owner === OWNER;
  } catch {
    return false;
  }
}

function stage() {
  const home = absoluteEnvPath(process.env.HOME, os.homedir(), 'HOME');
  const hermesHome = absoluteEnvPath(process.env.HERMES_HOME, path.join(home, '.hermes'), 'HERMES_HOME');
  assertDirectoryRoute(trustedAnchor(home, hermesHome), hermesHome, 'HERMES_HOME');
  const targets = discoverTargets(hermesHome);
  if (!targets.length) return 'skip:no-config';

  const parser = resolveYaml(hermesHome, home);
  if (!parser.YAML) return `skip:${parser.status}`;
  const { YAML } = parser;
  const snapshots = [];
  for (const target of targets) {
    const source = readSafeFile(target.config, 'Hermes config', MAX_CONFIG_BYTES);
    parseConfig(YAML, source);
    replaceConfigSkin(YAML, source);
    snapshots.push({ profile: target.profile, configSha256: hash(source) });
  }

  const { palette, theme, appearance } = validatePalette();
  const skin = skinYaml(palette, theme, appearance);
  const paths = stagePaths(home);
  assertDirectoryRoute(trustedAnchor(home, paths.cacheRoot), paths.cacheRoot, 'cache');
  ensurePrivateDirectory(paths.cacheRoot, ['dotfiles', 'hermes']);
  const manifest = `${JSON.stringify({
    owner: OWNER,
    version: 1,
    theme,
    appearance,
    skinSha256: hash(skin),
    targets: snapshots
  }, null, 2)}\n`;

  preflightOwnedOutput(paths.skin, 'staged skin', MAX_SKIN_BYTES, isOwnedSkin);
  preflightOwnedOutput(paths.manifest, 'stage manifest', MAX_STAGE_BYTES, isOwnedManifest);
  atomicWrite(paths.skin, skin, 0o600, { label: 'staged skin', owned: isOwnedSkin });
  atomicWrite(paths.manifest, manifest, 0o600, { label: 'stage manifest', owned: isOwnedManifest });
  return `staged:${targets.length}`;
}

function readManifest(paths) {
  const source = readSafeFile(paths.manifest, 'stage manifest', MAX_STAGE_BYTES);
  if (!isOwnedManifest(source)) fail('stage manifest is not owned by dotfiles');
  let manifest;
  try { manifest = JSON.parse(source); } catch { fail('stage manifest is invalid'); }
  if (manifest.version !== 1 || !Array.isArray(manifest.targets) ||
      typeof manifest.skinSha256 !== 'string' || !THEME_RE.test(manifest.theme || '') ||
      !['dark', 'light'].includes(manifest.appearance)) {
    fail('stage manifest is invalid');
  }
  for (const target of manifest.targets) {
    if (!target || typeof target !== 'object' ||
        (target.profile !== 'default' && !PROFILE_RE.test(target.profile || '')) ||
        !/^[0-9a-f]{64}$/.test(target.configSha256 || '')) fail('stage manifest is invalid');
  }
  return manifest;
}

function validateStagedSkin(YAML, source) {
  if (!isOwnedSkin(source)) fail('staged skin is not owned by dotfiles');
  let parsed;
  try { parsed = YAML.parse(source, { maxAliasCount: 0, uniqueKeys: true }); } catch { fail('staged skin is invalid'); }
  if (!parsed || parsed.name !== 'dotfiles' || !parsed.colors || typeof parsed.colors !== 'object' || Array.isArray(parsed.colors)) {
    fail('staged skin is invalid');
  }
  const expectedTokens = ['background', 'ui_text', 'ui_accent', 'ui_border', 'banner_dim', 'ui_error',
    'ui_ok', 'ui_warn', 'completion_menu_bg', 'completion_menu_current_bg', 'status_bar_bg'];
  for (const token of expectedTokens) {
    if (typeof parsed.colors[token] !== 'string' || !/^#[0-9a-f]{6}$/.test(parsed.colors[token])) fail('staged skin is invalid');
  }
}

function sameTargets(targets, manifestTargets) {
  if (targets.length !== manifestTargets.length) return false;
  return targets.every((target, index) => target.profile === manifestTargets[index].profile);
}

function publish() {
  const home = absoluteEnvPath(process.env.HOME, os.homedir(), 'HOME');
  const hermesHome = absoluteEnvPath(process.env.HERMES_HOME, path.join(home, '.hermes'), 'HERMES_HOME');
  assertDirectoryRoute(trustedAnchor(home, hermesHome), hermesHome, 'HERMES_HOME');
  const paths = stagePaths(home);
  assertDirectoryRoute(trustedAnchor(home, paths.cacheRoot), paths.cacheRoot, 'cache');
  if (!existingDirectory(paths.directory, 'stage directory')) return 'skip:no-stage';

  const targets = discoverTargets(hermesHome);
  if (!targets.length) return 'skip:no-config';
  const parser = resolveYaml(hermesHome, home);
  if (!parser.YAML) return `skip:${parser.status}`;
  const { YAML } = parser;
  const manifest = readManifest(paths);
  const skin = readSafeFile(paths.skin, 'staged skin', MAX_SKIN_BYTES);
  if (hash(skin) !== manifest.skinSha256) fail('staged skin changed after rendering');
  validateStagedSkin(YAML, skin);
  if (!sameTargets(targets, manifest.targets)) fail('Hermes profiles changed since staging');

  const prepared = [];
  for (let index = 0; index < targets.length; index += 1) {
    const target = targets[index];
    const snapshot = manifest.targets[index];
    const source = readSafeFile(target.config, 'Hermes config', MAX_CONFIG_BYTES);
    if (hash(source) !== snapshot.configSha256) fail('Hermes config changed since staging');
    const updated = replaceConfigSkin(YAML, source);
    const skins = path.join(target.home, 'skins');
    const skinsPresent = existingDirectory(skins, 'skins directory');
    const skinPath = path.join(skins, 'dotfiles.yaml');
    if (skinsPresent) {
      const existingSkin = safeRegularFile(skinPath, 'active skin', MAX_SKIN_BYTES, true);
      if (existingSkin && !isOwnedSkin(readSafeFile(skinPath, 'active skin', MAX_SKIN_BYTES))) {
        fail('active dotfiles skin is not owned by dotfiles');
      }
    } else {
      let skinRoute;
      try { skinRoute = fs.lstatSync(skins); } catch (error) { if (error.code !== 'ENOENT') fail('cannot inspect skins directory'); }
      if (skinRoute) fail('skins directory is not safe');
    }
    const backup = `${target.config}.dotfiles-theme.bak`;
    safeRegularFile(backup, 'config backup', MAX_CONFIG_BYTES, true);
    prepared.push({ ...target, source, updated, skins, skinPath, backup });
  }

  for (const target of prepared) {
    if (target.updated !== target.source) createBackupOnce(target.backup, target.source);
  }

  let skinsChanged = 0;
  for (const target of prepared) {
    if (!existingDirectory(target.skins, 'skins directory')) {
      try { fs.mkdirSync(target.skins, { mode: 0o700 }); } catch { fail('cannot create skins directory'); }
      if (!existingDirectory(target.skins, 'skins directory')) fail('skins directory is not safe');
    }
    if (atomicWrite(target.skinPath, skin, 0o600, { label: 'active skin', owned: isOwnedSkin })) skinsChanged += 1;
  }

  let configsChanged = 0;
  for (const target of prepared) {
    if (target.updated === target.source) continue;
    if (atomicWrite(target.config, target.updated, target.mode, {
      label: 'Hermes config',
      expectedHash: hash(target.source)
    })) configsChanged += 1;
  }
  return `published:${targets.length}:${skinsChanged}:${configsChanged}`;
}

function main() {
  const command = process.argv[2];
  if (command !== 'stage' && command !== 'publish') fail('expected stage or publish command');
  const result = command === 'stage' ? stage() : publish();
  process.stdout.write(`${result}\n`);
}

try {
  main();
} catch (error) {
  const message = error instanceof SafetyError ? error.message : 'unexpected internal failure';
  process.stderr.write(`Hermes theme error: ${message}\n`);
  process.exitCode = 1;
}
