"""Generate Zen's startup stylesheet. No extension, service, or browser automation."""
import sys
sys.dont_write_bytecode = True

import configparser
import os
from pathlib import Path
import stat
from string import Template
import tempfile

from palette import HERE, cache_dir, from_env, validate

HEADER = b'/* Generated by dotfiles Zen theme integration. Browser UI only. */\n'
IMPORT = HEADER + b'@import url("dotfiles-theme.css");\n'
PREFS = b'''// Dotfiles Zen: browser UI, native blur, and normal session restore.
user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);
user_pref("zen.widget.macos.window-vibrancy", true);
user_pref("browser.tabs.allow_transparent_browser", false);
user_pref("browser.startup.page", 3);
'''


def safe_path(path):
    if not path.is_absolute() or '..' in path.parts:
        raise ValueError('expected an absolute path without parent traversal')
    if any(part.is_symlink() for part in (path, *path.parents)):
        raise ValueError('refusing symlink: ' + str(path))


def read_optional(path):
    safe_path(path)
    try:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    except FileNotFoundError:
        return None
    with os.fdopen(fd, 'rb') as stream:
        info = os.fstat(stream.fileno())
        if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
            raise ValueError('expected a regular, non-hardlinked file: ' + str(path))
        data = stream.read(1024 * 1024 + 1)
    if len(data) > 1024 * 1024:
        raise ValueError('file too large: ' + str(path))
    return data


def find_profile(home):
    base = home / 'Library/Application Support/zen'
    override = os.environ.get('ZEN_PROFILE')
    if override:
        profile = Path(override)
    else:
        ini = read_optional(base / 'profiles.ini')
        if ini is None:
            return None
        parser = configparser.ConfigParser(interpolation=None)
        parser.read_string(ini.decode('utf-8'))
        defaults = {parser[s]['Default'] for s in parser.sections()
                    if s.startswith('Install') and parser[s].get('Default')}
        if not defaults:
            defaults = {parser[s]['Path'] for s in parser.sections()
                        if s.startswith('Profile') and parser[s].get('Default') == '1'}
        if len(defaults) != 1:
            raise ValueError('cannot identify one Zen profile; set ZEN_PROFILE explicitly')
        profile = base / defaults.pop()
    safe_path(profile)
    if not profile.is_relative_to(home) or not profile.is_dir():
        raise ValueError('Zen profile must be an existing directory inside HOME')
    return profile


def render_css(palette):
    p = validate(palette)
    values = {key: color[1:] for key, color in p['colors'].items()}
    values['BG_RGB'] = ', '.join(str(int(values['BG'][i:i + 2], 16)) for i in (0, 2, 4))
    values['OPACITY'] = format(p['opacity'], '.15g')
    return Template((HERE / 'templates/userChrome.css').read_text()).substitute(values).encode()


def publish(path, data, before):
    if data == before:
        return False
    safe_path(path)
    path.parent.mkdir(parents=True, mode=0o700, exist_ok=True)
    safe_path(path)
    fd, temporary = tempfile.mkstemp(prefix='.zen-theme-', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        if read_optional(path) != before:
            raise ValueError('file changed during rendering; left untouched: ' + str(path))
        if before is None:
            os.link(temporary, path)  # Exclusive publication: never overwrite a concurrent file.
        else:
            os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    return True


def configure(profile, palette, marker):
    css = profile / 'chrome/dotfiles-theme.css'
    userchrome = profile / 'chrome/userChrome.css'
    prefs = profile / 'user.js'
    old_css, old_import, old_prefs = (read_optional(p) for p in (css, userchrome, prefs))
    if old_css is not None and not old_css.startswith(HEADER):
        raise ValueError('existing stylesheet kept unchanged: ' + str(css))
    if old_import is not None and not old_import.startswith(IMPORT):
        raise ValueError('existing userChrome.css kept unchanged: ' + str(userchrome))
    if old_prefs is not None and not old_prefs.startswith(PREFS):
        raise ValueError('existing user.js kept unchanged: ' + str(prefs))
    old_marker = read_optional(marker)
    if old_marker not in (None, b'restart\n'):
        raise ValueError('unexpected restart marker; left unchanged')
    # Full preflight above; preserve additions to our import/preferences files.
    changes = [(css, render_css(palette), old_css),
               (prefs, old_prefs if old_prefs is not None else PREFS, old_prefs),
               (userchrome, old_import if old_import is not None else IMPORT, old_import)]
    changed = any(data != before for _, data, before in changes)
    if changed:
        # Keep a deferred restart across --no-reload and interrupted renders.
        publish(marker, b'restart\n', old_marker)
        for path, data, before in changes:
            publish(path, data, before)
    return changed


def main():
    try:
        profile = find_profile(Path.home())
        if profile is None:
            print('no-profile')
        else:
            changed = configure(profile, from_env(), cache_dir() / 'restart-needed')
            print('changed' if changed else 'unchanged')
        return 0
    except (OSError, ValueError, configparser.Error) as error:
        print('Zen configuration stopped: ' + str(error), file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
